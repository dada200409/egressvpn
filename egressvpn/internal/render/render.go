// xfrmIface is the XFRM interface a face's tunnels are bound to. config.Validate
// keeps face names short enough that this never hits IFNAMSIZ.
func xfrmIface(faceName string) string { return "xv" + faceName }

// ifID is the mark tying a Child_SA to xfrmIface() in both directions. It is an
// index into the kernel's xfrm interface table, so it must be unique per face and
// non-zero - 1-based, and the same value the link was created with.
func ifID(c *config.Config, faceName string) int {
	for i := range c.Faces {
		if c.Faces[i].Name == faceName {
			return i + 1
		}
	}
	panic("face " + faceName + " passed validation but is missing")
}

func cidrIP(s string) string {
	if i := strings.IndexByte(s, '/'); i >= 0 {
		return s[:i]
	}
	return s
}

// poolProbe is one address inside a face's pool, used by the reconciler to ask the
// FIB a question instead of parsing a route dump.
//
// The dump form (`ip route show exact <pool> dev <iface>`) cannot be used: when the
// query names the device, iproute2 prints the match without repeating it (measured
// on the deployed host: `10.90.1.0/24 scope link`), so any check on the device name
// fails against a healthy kernel and the reconciler would rebuild a fine face every
// minute. `ip route get <addr>` reports the interface the kernel would really use,
// which is the fact that decides whether a face can deliver a reply at all.
func poolProbe(pool string) string {
	_, n, err := net.ParseCIDR(pool)
	if err != nil {
		return cidrIP(pool)
	}
	ip := n.IP.To4()
	if ip == nil {
		return cidrIP(pool)
	}
	ip = ip.Mask(n.Mask)
	ip[len(ip)-1]++
	return ip.String()
}
